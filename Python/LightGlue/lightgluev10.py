def get_world_points_airsim(
        matched_satellite_pixels,
        heightmap,
        patch_transform,
    ):
    N = len(matched_satellite_pixels)
    world_points = np.zeros((N, 3))
    
    for i in range(N):
        su, sv = matched_satellite_pixels[i]
        x_tm06_estimated, y_tm06_estimated = patch_transform * (su, sv)
        world_points[i]=airsim2ecef.invertfromtm06([x_tm06_estimated, y_tm06_estimated, map_coordinates(heightmap, [[sv], [su]], order=1)[0]]) 
        
    
    # ============================================
    # SANITY CHECK before running PnP
    # ============================================
    print(f"World points range:")
    print(f"  X (North): [{world_points[:,0].min():.1f}, "
          f"{world_points[:,0].max():.1f}]")
    print(f"  Y (East):  [{world_points[:,1].min():.1f}, "
          f"{world_points[:,1].max():.1f}]")
    print(f"  Z (Down):  [{world_points[:,2].min():.1f}, "
          f"{world_points[:,2].max():.1f}]")
    return world_points

def bridge_to_real_pipeline(
    matched_drone_pixels,      # Nx2 from SP in ORIGINAL image
    matched_satellite_pixels,  # Nx2 from SP in satellite tile
    patch_transform,           # Orto pixel coordinate to tm06 coordinate
    heightmap,                 # function: (x,y) → z in NED
    K,                         # camera intrinsics
    img_path                   # Image path to acesss ground truth
):
    """
    Bridge from your existing matching to PnP.
    """
    error_array=[]
    # Convert satellite pixels to world 3D points
    world_points = get_world_points_airsim(matched_satellite_pixels, heightmap, patch_transform)
    
    gt = get_airsim_ground_truth(img_path)  # your function
    
    print(f"\nDrone GT position: ({gt[0]:.1f}, {gt[1]:.1f})")
    
    # ============================================
    # Run PnP
    # ============================================
    image_points = matched_drone_pixels.astype(np.float64)
    object_points = world_points.astype(np.float64)
    
    success, rvec, tvec, inliers = cv2.solvePnPRansac(
        object_points,
        image_points,
        K,
        distCoeffs=None,
        flags=cv2.SOLVEPNP_SQPNP,
        reprojectionError=8.0,
        confidence=0.99,
        iterationsCount=10000
    )
    
    if not success: #or len(inliers)<30:
        print("PnP FAILED")
        return None
    
    
    R_est, _ = cv2.Rodrigues(rvec)
    pos_est = (-R_est.T @ tvec).flatten()
    error_array.append(pos_est[0] - gt[0])
    error_array.append(pos_est[1] - gt[1])
    error_array.append(pos_est[2] - gt[2])
    forward = R_est.T @ np.array([0, 0, 1])
    
    print(f"\n=== PnP RESULT ===")
    print(f"Estimated position: ({pos_est[0]:.1f}, "
          f"{pos_est[1]:.1f}, {pos_est[2]:.1f})")
    print(f"GT position:        ({gt[0]:.1f}, "
          f"{gt[1]:.1f}, {gt[2]:.1f})")
    print(f"Position error: {np.linalg.norm(pos_est - gt):.2f}m \nPosition error [no height]: {np.linalg.norm(pos_est[:2] - gt[:2]):.2f}m")
    print(f"Position error [North]: "
          f"{pos_est[0] - gt[0]:.2f}m [East]{pos_est[1] - gt[1]:.2f}m")
    print(f"Altitude est: {-pos_est[2]:.1f}m, "
          f"GT: {-gt[2]:.1f}m")
    print(f"Forward position: ({forward[0]:.1f}, "
          f"{forward[1]:.1f}, {forward[2]:.1f})")
    print(f"Inliers: {len(inliers)}/{len(image_points)}")
    
    # Verify recovered orientation
    optical_axis = R_est.T @ np.array([0, 0, 1])
    pitch_recovered = np.degrees(np.arccos(
        np.clip(-optical_axis[2], -1, 1)
    ))
    print(f"Recovered pitch from vertical: {pitch_recovered:.1f}° "
          f"(expected ~80°)")
    
    error_u=[]
    error_v=[]
    img_pts_proj, _ = cv2.projectPoints(object_points, rvec, tvec, K, distCoeffs=None)
    for i in range(len(img_pts_proj)):
        u_proj,v_proj=img_pts_proj[i][0]
        u,v=image_points[i]
        error_u.append(u-u_proj)
        error_v.append(v-v_proj)
    error_u=np.array(error_u)
    error_v=np.array(error_v)
    print(f'U RMSE: {np.sqrt(np.mean(error_u**2)):2f}, V RMSE: {np.sqrt(np.mean(error_v**2)):2f}')
    
    success, rvec, tvec=cv2.solvePnP(
    object_points[inliers],
    image_points[inliers],
    K,
    None,
    rvec,
    tvec,
    useExtrinsicGuess=True
    )
    if not success:
        print("PnP Extrinsic Guess FAILED")
    
    R_est, _ = cv2.Rodrigues(rvec)
    pos_est = (-R_est.T @ tvec).flatten()
    error_array.append(pos_est[0] - gt[0])
    error_array.append(pos_est[1] - gt[1])
    error_array.append(pos_est[2] - gt[2])
    forward = R_est.T @ np.array([0, 0, 1])
    
    print(f"\n=== PnP Extrinsic RESULT ===")
    print(f"Estimated position: ({pos_est[0]:.1f}, "
          f"{pos_est[1]:.1f}, {pos_est[2]:.1f})")
    print(f"GT position:        ({gt[0]:.1f}, "
          f"{gt[1]:.1f}, {gt[2]:.1f})")
    print(f"Position error: "
          f"{np.linalg.norm(pos_est - gt):.2f}m")
    print(f"Position error [no height]: "
          f"{np.linalg.norm(pos_est[:2] - gt[:2]):.2f}m")
    print(f"Position error [North]: "
          f"{pos_est[0] - gt[0]:.2f}m [East]{pos_est[1] - gt[1]:.2f}m")
    print(f"Forward position: ({forward[0]:.1f}, "
          f"{forward[1]:.1f}, {forward[2]:.1f})")
    print(f"Altitude est: {-pos_est[2]:.1f}m, "
          f"GT: {-gt[2]:.1f}m")
    

    dir_gt = (gt[:2] - C0) / np.linalg.norm(gt[:2]-C0)
    dir_est = (pos_est[:2] - C0) / np.linalg.norm(pos_est[:2]-C0)

    cos_angle = np.dot(dir_gt, dir_est)
    angle = np.arccos(np.clip(cos_angle, -1.0, 1.0))
    angle_deg = np.degrees(angle)

    error = pos_est[:2] - gt[:2]

    # perpendicular component
    error_perp = error - np.dot(error, dir_gt) * dir_gt
    lateral_error = np.linalg.norm(error_perp)

    def signed_angle(a, b):
        return np.degrees(np.arctan2(
            a[0]*b[1] - a[1]*b[0],
            np.dot(a, b)
        ))

    angle_deg = signed_angle(dir_gt, dir_est)

    print(f"Direction angle: {angle_deg}º, "
          f"Cross angle: {lateral_error}º")
    
    distance = np.linalg.norm(gt[:2] - C0)
    error = np.linalg.norm(error)

    print(f"Distance: {distance}m, "
          f"Error: {error}m")
    
    error_array.append(len(inliers))
    error_array.append(len(inliers)/len(image_points))
    error_array.append(np.sqrt(np.mean(error_u**2)))
    error_array.append(np.sqrt(np.mean(error_v**2)))
    global_error.append(error_array)
    return pos_est

