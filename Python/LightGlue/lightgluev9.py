    #patch_center_x_px = crop_size_px / 2.0
    #patch_center_y_px = crop_size_px / 2.0

    # 2. Convert that center pixel to TM06
    #test_x_tm06, test_y_tm06 = patch_transform * (patch_center_x_px, patch_center_y_px)

    # 3. Convert to GPS and print
    #test_lon, test_lat = TRANSFORMER_TO_GPS.transform(test_x_tm06, test_y_tm06)
